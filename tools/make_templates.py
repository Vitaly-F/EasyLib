# Extracts Altium-saved record templates from AltiumSharp TestData fixtures into Templates.cs
import olefile, struct, sys, zlib, base64
G='/tmp/claude-0/-home-claude/8775db08-0afb-5879-9c2a-de693d5c05a5/scratchpad/ref/AltiumSharp/TestData/Generated/Individual/'
def blocks_prims(data):
    i=0
    nlen=struct.unpack('<I',data[0:4])[0]; i=4+nlen
    prims=[]
    def blk():
        nonlocal i
        ln=struct.unpack('<I',data[i:i+4])[0]&0xffffff; b=data[i+4:i+4+ln]; i+=4+ln; return b
    while i<len(data):
        t=data[i]; i+=1
        if t==2: bl=[blk() for _ in range(6)]
        elif t==5: bl=[blk(),blk()]
        else: bl=[blk()]
        prims.append((t,bl))
    return prims
def comp_prims(fn):
    f=olefile.OleFileIO(G+'PCB/'+fn)
    for e in f.listdir():
        if len(e)==2 and e[1]=='Data' and e[0] not in ('Library','FileVersionInfo'):
            return blocks_prims(f.openstream('/'.join(e)).read())
def first(fn,t,idx=0):
    return [bl for tt,bl in comp_prims(fn) if tt==t][0][idx]
lib=olefile.OleFileIO(G+'PCB/PAD_SMD_RECTANGULAR.PcbLib')
libdata=lib.openstream('Library/Data').read()
ln=struct.unpack('<I',libdata[:4])[0]&0xffffff
header_text=libdata[4:4+ln].rstrip(b'\x00')
T={}
T['PcbLibDataHeader']=zlib.compress(header_text,9)
T['PcbFileVersionInfo']=zlib.compress(lib.openstream('FileVersionInfo/Data').read(),9)
T['PcbLayerKindMapping']=lib.openstream('Library/LayerKindMapping/Data').read()
T['PcbEmbeddedFonts']=lib.openstream('Library/EmbeddedFonts').read()
T['PadSmdMain']=first('PAD_SMD_RECTANGULAR.PcbLib',2,4)
T['PadThMain']=first('PAD_TH_ROUND.PcbLib',2,4)
T['PadSlotMain']=first('PAD_TH_SLOT.PcbLib',2,4)
T['PadSlotSizeShape']=first('PAD_TH_SLOT.PcbLib',2,5)
T['Track']=first('TRACK_WIDTHS.PcbLib',4)
T['Arc']=first('ARCS_TEST.PcbLib',1)
sch=olefile.OleFileIO(G+'SchLib/RESISTOR.SchLib')
T['SchStorage']=sch.openstream('Storage').read()
fh=sch.openstream('FileHeader').read()
txt=fh[4:].rstrip(b'\x00').decode('latin1')
prefix=txt[:txt.index('|CompCount=')]
assert len(T['PadSmdMain'])==202 and len(T['PadThMain'])==202 and len(T['PadSlotSizeShape'])==651
assert len(T['Track'])==49 and len(T['Arc'])==60
out=['// Generated by tools/make_templates.py from Altium-saved fixture files (AltiumSharp TestData).',
     '// Record byte templates; geometry fields are overwritten at known offsets by AltiumLib.cs.',
     'namespace EasyLib','{','    static class Templates','    {']
for k,v in T.items():
    out.append('        public const string %s = "%s";'%(k, base64.b64encode(v).decode()))
out.append('        public const string SchHeaderPrefix = "%s";'%prefix.replace('\\','\\\\').replace('"','\\"'))
out+=['    }','}']
open('/home/claude/EasyLib2/src/Templates.cs','w').write('\n'.join(out)+'\n')
print({k:len(v) for k,v in T.items()}, len(prefix))
print(prefix)
